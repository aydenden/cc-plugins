#!/usr/bin/env bash
# cmux-dispatch.sh — Run opencode in a cmux split via IPC (Pattern B').
# Usage: cmux-dispatch.sh <task_type> <project_dir> <prompt_file> [model_override]
#
# Layout strategy:
#   - First delegate creates ROOT surface via `cmux new-split right` (main pane | root)
#   - Parallel delegates nest inside ROOT via `cmux new-split down --surface $ROOT`
#     so the main pane area is never further sliced.
#   - Completion: parent blocks on `cmux wait-for <signal>` sent by the child.
#                 Owns surface is closed via `cmux close-surface`; the last
#                 delegate also closes ROOT.
#
# Exit codes:
#   0..N    opencode's own exit code
#   127     cmux unavailable — caller should fall back to SSE (safe-oc.sh)
set -uo pipefail

TASK_TYPE="${1:?task_type required}"
PROJECT_DIR="${2:?project_dir required}"
PROMPT_FILE="${3:?prompt_file required}"
MODEL_OVERRIDE="${4:-}"

PLUGIN_ROOT="${CLAUDE_PLUGIN_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"

# Require cmux on PATH and responsive.
if ! command -v cmux >/dev/null 2>&1; then
  echo "[cmux-dispatch] cmux not in PATH — fallback signal" >&2
  exit 127
fi
if ! cmux --help >/dev/null 2>&1; then
  echo "[cmux-dispatch] cmux CLI not responding (need CMUX_SOCKET_MODE=allowAll outside cmux?)" >&2
  exit 127
fi

PERM_FILE="$PLUGIN_ROOT/config/perm-${TASK_TYPE}.json"
if [ ! -f "$PERM_FILE" ]; then
  echo "ERROR: permission file not found: $PERM_FILE" >&2
  exit 1
fi

AGENT="oc-${TASK_TYPE}"

# Ensure the agent is registered (mirrors safe-oc.sh)
OC_CONFIG_FILE="${OPENCODE_CONFIG_DIR:-$HOME/.config/opencode}/opencode.json"
if [ -f "$OC_CONFIG_FILE" ] && command -v jq >/dev/null 2>&1; then
  if ! jq -e --arg a "$AGENT" '.agent[$a] // empty' "$OC_CONFIG_FILE" >/dev/null 2>&1; then
    "$PLUGIN_ROOT/bin/install-agents.sh" --force >&2 || \
      echo "[cmux-dispatch] WARNING: agent registration failed" >&2
  fi
fi

# Wall-clock per task type (same table as safe-oc.sh)
case "$TASK_TYPE" in
  summarize)   WALL=300  ;;
  single-file) WALL=480  ;;
  refactor)    WALL=600  ;;
  implement)   WALL=1800 ;;
  cjk-doc)     WALL=600  ;;
  research)    WALL=1200 ;;
  compose)     WALL=900  ;;
  analyze)     WALL=900  ;;
  batch)       WALL=3600 ;;
  *)           WALL=600  ;;
esac

SESSION_ID="${CC_OC_SESSION_ID:-$(uuidgen 2>/dev/null || date +%s-$$)}"
SESSION_DIR="/tmp/cc-oc-$SESSION_ID"
mkdir -p "$SESSION_DIR"
echo "$PROJECT_DIR" > "$SESSION_DIR/workdir"
echo "cmux-ipc"    > "$SESSION_DIR/mode"

# Shared state for root surface across parallel delegates.
STATE_DIR="${CC_OC_CMUX_STATE_DIR:-/tmp/cc-oc-cmux}"
mkdir -p "$STATE_DIR"
ROOT_FILE="$STATE_DIR/root.surface"
REFCOUNT_FILE="$STATE_DIR/refcount"
LOCK_DIR="$STATE_DIR/lock.d"

# mkdir-based lock (portable across macOS bash 3.2 — no `flock` dependency)
acquire_lock() {
  local tries=0
  while ! mkdir "$LOCK_DIR" 2>/dev/null; do
    tries=$((tries + 1))
    if [ "$tries" -gt 200 ]; then
      echo "[cmux-dispatch] lock timeout" >&2
      return 1
    fi
    sleep 0.05
  done
}
release_lock() { rmdir "$LOCK_DIR" 2>/dev/null || true; }

extract_surface() {
  grep -oE 'surface:[A-Za-z0-9_-]+' | head -1
}

# Acquire/create ROOT and increment refcount.
acquire_lock || exit 1

if [ -s "$ROOT_FILE" ]; then
  ROOT_SURFACE="$(cat "$ROOT_FILE")"
else
  REF="$(cmux new-split right 2>/dev/null | extract_surface)"
  if [ -z "$REF" ]; then
    release_lock
    echo "ERROR: cmux new-split right failed" >&2
    exit 1
  fi
  ROOT_SURFACE="$REF"
  echo "$ROOT_SURFACE" > "$ROOT_FILE"
fi

CUR_REFS="$(cat "$REFCOUNT_FILE" 2>/dev/null || echo 0)"
NEW_REFS=$((CUR_REFS + 1))
echo "$NEW_REFS" > "$REFCOUNT_FILE"

if [ "$NEW_REFS" -eq 1 ]; then
  MY_SURFACE="$ROOT_SURFACE"
else
  REF="$(cmux new-split down --surface "$ROOT_SURFACE" 2>/dev/null | extract_surface)"
  if [ -z "$REF" ]; then
    echo "$CUR_REFS" > "$REFCOUNT_FILE"   # rollback
    release_lock
    echo "ERROR: cmux new-split down --surface $ROOT_SURFACE failed" >&2
    exit 1
  fi
  MY_SURFACE="$REF"
fi

release_lock

echo "$MY_SURFACE"   > "$SESSION_DIR/surface"
echo "$ROOT_SURFACE" > "$SESSION_DIR/root_surface"

# Worker script invoked inside the surface. Writes exit_code, signals parent.
TASK_SCRIPT="$SESSION_DIR/task.sh"
SIGNAL="oc-done-$SESSION_ID"

MODEL_ARG=""
if [ -n "$MODEL_OVERRIDE" ]; then
  MODEL_ARG="--model \"$MODEL_OVERRIDE\""
fi

cat > "$TASK_SCRIPT" <<EOF
#!/usr/bin/env bash
# Auto-generated by cmux-dispatch.sh — session $SESSION_ID
set -uo pipefail
export OPENCODE_PERMISSION="\$(cat "$PERM_FILE")"
export OPENCODE_DISABLE_AUTOUPDATE=1
opencode run \\
  --dir "$PROJECT_DIR" \\
  --agent "$AGENT" \\
  --format json \\
  --title "[cc-bridge] $TASK_TYPE \$(date +%H%M%S)" $MODEL_ARG \\
  < "$PROMPT_FILE" \\
  > "$SESSION_DIR/oc.ndjson" \\
  2> "$SESSION_DIR/oc.stderr"
RC=\$?
echo "\$RC" > "$SESSION_DIR/exit_code"
cmux wait-for --signal "$SIGNAL" >/dev/null 2>&1 || true
EOF
chmod +x "$TASK_SCRIPT"

# Send command to the surface (cmux interprets literal \n as Enter)
if ! cmux send --surface "$MY_SURFACE" "bash $TASK_SCRIPT\n" >/dev/null 2>&1; then
  echo "ERROR: cmux send failed" >&2
  cleanup_surface() { :; }   # fall through to cleanup below
  WAIT_RC=1
else
  cmux wait-for "$SIGNAL" --timeout "$WALL" >/dev/null 2>&1
  WAIT_RC=$?
fi

EXIT_CODE="$(cat "$SESSION_DIR/exit_code" 2>/dev/null || echo "$WAIT_RC")"

# Cleanup: close own surface, decrement refcount, close ROOT if last.
acquire_lock || true
CUR_REFS="$(cat "$REFCOUNT_FILE" 2>/dev/null || echo 1)"
NEW_REFS=$((CUR_REFS - 1))
[ "$NEW_REFS" -lt 0 ] && NEW_REFS=0
echo "$NEW_REFS" > "$REFCOUNT_FILE"

if [ "$MY_SURFACE" != "$ROOT_SURFACE" ]; then
  cmux close-surface --surface "$MY_SURFACE" >/dev/null 2>&1 || true
fi
if [ "$NEW_REFS" -eq 0 ]; then
  cmux close-surface --surface "$ROOT_SURFACE" >/dev/null 2>&1 || true
  rm -f "$ROOT_FILE" "$REFCOUNT_FILE"
fi
release_lock

echo "session=$SESSION_ID task=$TASK_TYPE exit=$EXIT_CODE dir=$SESSION_DIR mode=cmux-ipc"
exit "$EXIT_CODE"
